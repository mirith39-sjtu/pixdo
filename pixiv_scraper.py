def _tag_cache_path():
    return CONFIG.get("tag_cache_file") or os.path.join(_base_dir, "tag_suggest_cache.json")


def _load_tag_cache():
    try:
        with open(_tag_cache_path(), encoding="utf-8") as f:
            data = json.load(f)
        if isinstance(data, dict):
            if not isinstance(data.get("queries"), dict):
                data["queries"] = {}
            if not isinstance(data.get("pool"), dict):
                data["pool"] = {}
            return data
    except Exception:
        pass
    return {"queries": {}, "pool": {}}


def _save_tag_cache(cache):
    """写缓存；顺带控制规模，防止无限增长"""
    try:
        q = cache.get("queries") or {}
        if len(q) > 2000:
            for k in list(q.keys())[:500]:
                q.pop(k, None)
        pool = cache.get("pool") or {}
        if len(pool) > 20000:
            items = sorted(pool.values(),
                           key=lambda x: -int(x.get("access_count") or 0))
            cache["pool"] = {it["tag_name"]: it for it in items[:15000]}
        path = _tag_cache_path()
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(cache, f, ensure_ascii=False)
        os.replace(tmp, path)
    except Exception:
        pass


def _norm_candidate(c):
    try:
        count = int(c.get("access_count") or 0)
    except (TypeError, ValueError):
        count = 0
    return {"tag_name": str(c.get("tag_name") or "").strip(),
            "translation": str(c.get("tag_translation") or "").strip(),
            "access_count": count,
            "type": str(c.get("type") or "")}


def _search_tag_pool(pool, keyword, limit):
    """离线回退：在历史标签池里做子串匹配（名称/翻译）。
    简繁与异体字归一后匹配（如 圣娅→圣亚、园→園），前缀优先、热度次之。"""
    kw = keyword.lower()
    if not kw:
        return []
    kwc = _tag_canon(kw)
    scored = []
    for it in (pool or {}).values():
        name = it.get("tag_name") or ""
        trans = it.get("translation") or ""
        nl, tl = name.lower(), trans.lower()
        nlc = _tag_canon(nl)
        tlc = _tag_canon(tl) if tl else ""
        hit = (kw in nl) or (tl and kw in tl) or \
              (kwc and (kwc in nlc or (tlc and kwc in tlc)))
        if hit:
            prefix = nl.startswith(kw) or (tl and tl.startswith(kw)) or \
                     (kwc and (nlc.startswith(kwc) or (tlc and tlc.startswith(kwc))))
            scored.append((0 if prefix else 1,
                           -int(it.get("access_count") or 0), it))
    scored.sort(key=lambda x: (x[0], x[1]))
    return [it for _, _, it in scored[:limit]]


