def ensure_logged_in(driver):
    if load_cookies(driver):
        driver.refresh()
        time.sleep(2)
        state = _session_logged_in(_make_session(driver.get_cookies()))
        if state is True:
            _log("[✓] Cookie 有效（已登录）")
            return
        if state is None:
            _log("[!] 无法验证登录状态（网络问题？），将按未登录处理")
        else:
            _log("[!] Cookie 已失效（服务器判定为未登录），删除旧 Cookie 并重新登录")
        try:
            os.remove(CONFIG["cookie_file"])
        except OSError:
            pass
    manual_login(driver)


