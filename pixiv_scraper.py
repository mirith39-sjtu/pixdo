def _get_file_version(exe_path):
    """读取 exe 文件的 ProductVersion（如 '152.0.4191.53'），失败返回 None"""
    try:
        import ctypes
        from ctypes import wintypes
        size = ctypes.windll.version.GetFileVersionInfoSizeW(exe_path, None)
        if not size:
            return None
        buf = ctypes.create_string_buffer(size)
        if not ctypes.windll.version.GetFileVersionInfoW(exe_path, 0, size, buf):
            return None
        p = ctypes.c_void_p()
        ln = wintypes.UINT()
        if not ctypes.windll.version.VerQueryValueW(buf, r"\VarFileInfo\Translation",
                                                    ctypes.byref(p), ctypes.byref(ln)):
            return None
        import struct
        lang, codepage = struct.unpack("HH", ctypes.string_at(p, 4))
        sub = rf"\StringFileInfo\{lang:04X}{codepage:04X}\ProductVersion"
        if not ctypes.windll.version.VerQueryValueW(buf, sub,
                                                    ctypes.byref(p), ctypes.byref(ln)):
            return None
        return ctypes.wstring_at(p, ln.value - 1)
    except Exception:
        return None


def _ver_tuple(v):
    """'152.0.4191.53' -> (152, 0, 4191, 53)，解析失败返回空元组"""
    try:
        return tuple(int(x) for x in str(v).split("."))
    except Exception:
        return ()


def _find_driver(browser_type, browser_path=None):
    """查找 WebDriver 路径。
    优先级: CONFIG 指定路径 > PATH 中的驱动 > Selenium 缓存中与浏览器
    主版本匹配的驱动 > 返回 None（交由 Selenium Manager 自动下载）。
    """
    specified = CONFIG.get("webdriver_path")
    if specified and os.path.isfile(specified):
        return specified
    name = {"edge": "msedgedriver.exe", "chrome": "chromedriver.exe"}.get(browser_type, "")
    if not name:
        return None

    # 1) PATH 中查找（用户自行管理的驱动优先，但最终仍会做版本校验）
    r = subprocess.run(["where", name], capture_output=True, text=True, shell=True)
    if r.returncode == 0 and r.stdout.strip():
        return r.stdout.strip().split("\n")[0]

    # 2) Selenium Manager 缓存目录中查找与浏览器主版本匹配的驱动
    cache_dir = os.path.join(os.path.expanduser("~"), ".cache", "selenium",
                             "msedgedriver" if browser_type == "edge" else "chromedriver",
                             "win64")
    if os.path.isdir(cache_dir):
        bp = browser_path or _find_browser()[1]
        bver = _get_file_version(bp) or ""
        bmajor = _ver_tuple(bver)[:1]  # 浏览器主版本，如 (152,)
        cands = []
        for ver in os.listdir(cache_dir):
            dp = os.path.join(cache_dir, ver, name)
            if os.path.isfile(dp):
                cands.append((_ver_tuple(ver), ver, dp))
        if not cands:
            return None
        # 优先选择主版本匹配中数值最大的
        matched = [c for c in cands if bmajor and c[0][:1] == bmajor]
        chosen = sorted(matched if matched else cands,
                        key=lambda c: c[0], reverse=True)[0]
        if matched:
            _log(f"[*] 使用缓存驱动: {chosen[2]} (浏览器主版本 {bmajor[0]})")
            return chosen[2]
        _log(f"[!] 缓存驱动主版本 {chosen[0][0]} 与浏览器主版本 "
             f"{bmajor[0] if bmajor else '未知'} 不匹配，忽略缓存")
    return None


def create_driver():
    bt, bp = _find_browser()
    is_edge = bt == "edge"
    opts = EdgeOpts() if is_edge else ChromeOpts()
    svc_cls = EdgeSvc if is_edge else ChromeSvc

    if not CONFIG["show_browser"]:
        opts.add_argument("--headless=new")
        opts.add_argument("--window-size=1920,1080")
    opts.add_argument("--disable-blink-features=AutomationControlled")
    opts.add_experimental_option("excludeSwitches", ["enable-automation"])
    opts.add_experimental_option("useAutomationExtension", False)
    opts.add_argument("--no-sandbox")
    opts.add_argument("--disable-gpu")
    opts.add_argument(f"--user-agent={UA}")
    opts.add_argument("--lang=ja-JP")
    opts.binary_location = bp

    dp = _find_driver(bt, bp)
    _log(f"[*] 浏览器: {bt}  ({bp})")
    if dp:
        _log(f"[*] 使用 WebDriver: {dp}")
    else:
        _log("[*] 未找到匹配的 WebDriver，将尝试自动下载（需要网络）...")
    try:
        driver = webdriver.Edge(service=svc_cls(dp) if dp else svc_cls(), options=opts) \
            if is_edge else \
            webdriver.Chrome(service=svc_cls(dp) if dp else svc_cls(), options=opts)
    except Exception as e:
        if "version" in str(e).lower() and "only supports" in str(e).lower():
            raise RuntimeError(
                f"WebDriver 与浏览器版本不匹配，无法启动浏览器。\n"
                f"详情: {e}\n"
                f"解决: 删除 ~/.cache/selenium/{'msedgedriver' if is_edge else 'chromedriver'}"
                f" 目录后重试（将自动下载匹配版本），或手动下载匹配的 WebDriver"
                f" 并在 CONFIG['webdriver_path'] 中指定。")
        raise

    # 仅隐藏最基本的 webdriver 标记（手动登录无需过多伪装）
    driver.execute_cdp_cmd("Page.addScriptToEvaluateOnNewDocument", {"source": """
        Object.defineProperty(navigator, 'webdriver', {get: () => undefined});
    """})
    return driver


def save_cookies(driver):
    with open(CONFIG["cookie_file"], "wb") as f:
        pickle.dump(driver.get_cookies(), f)
    _log(f"[*] Cookie 已保存")


def load_cookies(driver):
    cf = CONFIG["cookie_file"]
    if not os.path.exists(cf):
        return False
    driver.get("https://www.pixiv.net/")
    time.sleep(1.5)
    with open(cf, "rb") as f:
        cookies = pickle.load(f)
    ok = 0
    for c in cookies:
        for k in ("sameSite", "httpOnly", "storeId", "hostOnly", "session"):
            c.pop(k, None)
        if "expiry" in c:
            try:
                c["expiry"] = int(float(c["expiry"]))
            except (ValueError, OverflowError):
                c.pop("expiry", None)
        try:
            driver.add_cookie(c)
            ok += 1
        except Exception:
            pass
    _log(f"[*] Cookie 加载: {ok}/{len(cookies)}")
    return ok > 0


def _make_session(cookie_dicts):
    """由 selenium 格式的 cookie 列表构造 requests 会话（校验/爬取共用）"""
    s = requests.Session()
    s.headers.update({"User-Agent": UA, "Referer": "https://www.pixiv.net/",
                      "Accept-Language": "ja-JP,ja;q=0.9,en;q=0.8"})
    for c in cookie_dicts:
        n, v = c.get("name", ""), c.get("value", "")
        if not n:
            continue
        s.cookies.set(n, v, domain=c.get("domain", ".pixiv.net"),
                      path=c.get("path", "/"))
        if n == "PHPSESSID":
            s.cookies.set(n, v, domain=".pximg.net", path="/")  # 图片 CDN
    return s


def _homepage_logged_in(session):
    """兜底校验: 解析首页服务端渲染的登录标记，返回 True/False/None"""
    try:
        h = session.get("https://www.pixiv.net/", timeout=15).text
    except Exception:
        return None
    if r'\"self\":null' in h or '"isLoggedIn":false' in h:
        return False
    if r'\"self\":{' in h or '"isLoggedIn":true' in h:
        return True
    return None


def _session_logged_in(session):
    """真实登录校验。返回 True/False，无法判断时返回 None。
    注意: pixiv 对游客也会发放 PHPSESSID，不能只看 cookie 名字！
    这里调用需要登录的接口: 游客会得到 401，登录用户返回 200。"""
    try:
        r = session.get("https://www.pixiv.net/ajax/follow_latest/illust"
                        "?p=1&mode=all&lang=ja", timeout=10)
    except Exception:
        return None
    if r.status_code == 200:
        try:
            return not r.json().get("error", False)
        except Exception:
            return _homepage_logged_in(session)
    if r.status_code == 401:
        return False
    return _homepage_logged_in(session)


