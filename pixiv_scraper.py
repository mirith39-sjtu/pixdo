_HIST_COLS = ("illust_id title author author_id like_count is_r18 page_count "
              "tags url status reason folder files created_at updated_at").split()


def _file_ok(path):
    """文件存在且非空"""
    try:
        return os.path.getsize(path) > 0
    except OSError:
        return False


def _now():
    return time.strftime("%Y-%m-%d %H:%M:%S")


class HistoryStore:
    """跨运行查重表。

    状态:
      downloaded = 全部页面都在(将被跳过, 不再下载)
      missing    = 图片被手动删除/下载不完整(重新出现时补下载缺失的页)
      filtered   = 被过滤条件排除(低赞/AI 等; 默认也跳过, 可把
                   dedup_skip_filtered 设为 False 让它们每次重新检查)

    手动删除图片的同步:
      每次运行开始时 reconcile() 会检查所有记录的文件是否还在,
      被删除的记录自动标记为 missing; 该作品下次出现时会重新下载。
      运行中遇到文件缺失的也会即时改状态。
    """

    _UPSERT = """INSERT INTO works
        (illust_id,title,author,author_id,like_count,is_r18,page_count,
         tags,url,status,reason,folder,files,created_at,updated_at)
        VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
        ON CONFLICT(illust_id) DO UPDATE SET
            title=excluded.title, author=excluded.author,
            author_id=excluded.author_id, like_count=excluded.like_count,
            is_r18=excluded.is_r18, page_count=excluded.page_count,
            tags=excluded.tags, url=excluded.url, status=excluded.status,
            reason=excluded.reason, folder=excluded.folder,
            files=excluded.files, updated_at=excluded.updated_at"""

    def __init__(self, db_path, skip_filtered=True):
        self.db_path = db_path
        self.skip_filtered = skip_filtered
        self.conn = None
        self.records = {}

    # ---------------- 基础 ----------------
    def open(self):
        self.conn = sqlite3.connect(self.db_path, timeout=10)
        self.conn.execute("""CREATE TABLE IF NOT EXISTS works (
            illust_id  TEXT PRIMARY KEY,
            title      TEXT,
            author     TEXT,
            author_id  TEXT,
            like_count INTEGER,
            is_r18     INTEGER,
            page_count INTEGER,
            tags       TEXT,
            url        TEXT,
            status     TEXT,
            reason     TEXT,
            folder     TEXT,
            files      TEXT,
            created_at TEXT,
            updated_at TEXT)""")
        self.conn.commit()
        self.records = {}
        for row in self.conn.execute(f"SELECT {','.join(_HIST_COLS)} FROM works"):
            rec = dict(zip(_HIST_COLS, row))
            try:
                files = json.loads(rec.get("files") or "[]")
            except Exception:
                files = []
            rec["file_list"] = files if isinstance(files, list) else []
            self.records[str(rec["illust_id"])] = rec

    def close(self):
        if self.conn is not None:
            try:
                self.conn.close()
            finally:
                self.conn = None

    def summary(self):
        n = {"downloaded": 0, "missing": 0, "filtered": 0}
        for r in self.records.values():
            if r.get("status") in n:
                n[r["status"]] += 1
        return (f"共 {len(self.records)} 条（已下载 {n['downloaded']} / "
                f"文件缺失 {n['missing']} / 已过滤 {n['filtered']}）")

    # ---------------- 文件状态 ----------------
    @staticmethod
    def is_complete(rec):
        """记录中的文件是否齐全（数量够页数 且 文件都存在且非空）"""
        files = rec.get("file_list") or []
        if not files or len(files) < int(rec.get("page_count") or 1):
            return False
        return all(_file_ok(p) for p in files)

    def reconcile(self):
        """对账: 表里的文件被手动删除/恢复后同步状态。返回变更条数"""
        changed = 0
        for rec in self.records.values():
            if rec.get("status") not in ("downloaded", "missing"):
                continue
            new = "downloaded" if self.is_complete(rec) else "missing"
            if new != rec["status"]:
                rec["status"] = new
                self._set_status(rec)
                changed += 1
        return changed

    def _set_status(self, rec):
        try:
            self.conn.execute("UPDATE works SET status=?, updated_at=? WHERE illust_id=?",
                              (rec["status"], _now(), rec["illust_id"]))
            self.conn.commit()
        except Exception:
            pass

    # ---------------- 查询 ----------------
    def should_skip(self, illust_id, is_ugoira=False):
        """是否需要跳过。返回 (skip, reason)"""
        rec = self.records.get(str(illust_id))
        if not rec:
            return False, ""
        st = rec.get("status")
        if st == "downloaded":
            files = rec.get("file_list") or []
            # 动图：旧记录里没有 .gif（过去只能下到静态首帧）→ 当作未完成重新下载
            if is_ugoira and not any(str(f).lower().endswith(".gif") for f in files):
                rec["status"] = "missing"
                self._set_status(rec)
                return False, ""
            if self.is_complete(rec):
                return True, "已下载"
            # 文件已被删除 → 更新表, 当作未处理
            rec["status"] = "missing"
            self._set_status(rec)
            return False, ""
        if st == "filtered" and self.skip_filtered:
            return True, "已过滤"
        return False, ""

    def files_of(self, illust_id):
        rec = self.records.get(str(illust_id))
        return list(rec.get("file_list") or []) if rec else []

    # ---------------- 写入 ----------------
    def _upsert(self, rec):
        self.conn.execute(self._UPSERT, (
            rec["illust_id"], rec.get("title", ""), rec.get("author", ""),
            rec.get("author_id", ""), rec.get("like_count", 0),
            1 if rec.get("is_r18") else 0, rec.get("page_count", 1),
            rec.get("tags", "[]"), rec.get("url", ""), rec.get("status", ""),
            rec.get("reason", ""), rec.get("folder", ""), rec.get("files", "[]"),
            rec.get("created_at", _now()), rec.get("updated_at", _now())))
        self.conn.commit()
        self.records[str(rec["illust_id"])] = rec

    def record_downloaded(self, d, folder, files, expected):
        """记录已处理的作品。files: 实际存在的文件列表; expected: 应有页数"""
        lid = str(d["illust_id"])
        present = [f for f in files if _file_ok(f)]
        now = _now()
        old = self.records.get(lid) or {}
        complete = expected > 0 and len(present) >= expected
        rec = {
            "illust_id": lid,
            "title": d.get("title", ""),
            "author": d.get("author", ""),
            "author_id": str(d.get("author_id", "")),
            "like_count": int(d.get("like_count") or 0),
            "is_r18": 1 if d.get("is_r18") else 0,
            "page_count": int(expected or d.get("page_count") or 1),
            "tags": json.dumps(d.get("tags") or [], ensure_ascii=False),
            "url": d.get("url", ""),
            "status": "downloaded" if complete else "missing",
            "reason": "",
            "folder": folder,
            "files": json.dumps(present, ensure_ascii=False),
            "created_at": old.get("created_at") or now,
            "updated_at": now,
        }
        rec["file_list"] = present
        self._upsert(rec)

    def record_filtered(self, d, reason):
        """记录被过滤的作品（低赞/AI/R18模式不符等）"""
        lid = str(d["illust_id"])
        old = self.records.get(lid) or {}
        now = _now()
        rec = {
            "illust_id": lid,
            "title": d.get("title", ""),
            "author": d.get("author", ""),
            "author_id": str(d.get("author_id", "")),
            "like_count": int(d.get("like_count") or 0),
            "is_r18": 1 if d.get("is_r18") else 0,
            "page_count": int(d.get("page_count") or 1),
            "tags": json.dumps(d.get("tags") or [], ensure_ascii=False),
            "url": d.get("url", ""),
            "status": "filtered",
            "reason": reason,
            "folder": old.get("folder", ""),
            "files": old.get("files") or "[]",
            "created_at": old.get("created_at") or now,
            "updated_at": now,
        }
        rec["file_list"] = old.get("file_list") or []
        self._upsert(rec)


def clear_history():
    """清空查重记录（删除数据库文件）。返回 (是否成功, 消息)"""
    path = CONFIG.get("history_db")
    if not path:
        return False, "未配置查重库路径"
    try:
        removed = False
        for suffix in ("", "-wal", "-shm", "-journal"):
            p = path + suffix
            if os.path.exists(p):
                os.remove(p)
                removed = True
        return True, (f"查重记录已清空: {path}" if removed else "查重记录本来就是空的")
    except OSError as e:
        return False, f"清空失败（文件可能被占用）: {e}"


