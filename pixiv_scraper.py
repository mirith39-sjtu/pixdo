def sanitize(name: str) -> str:
    return re.sub(r'[\\/:*?"<>|]', "_", name)[:120]


def has_ai_tag(tags):
    """标签中是否含 AI 关键词（大小写不敏感）"""
    if not tags or not CONFIG.get("ai_tags"):
        return False
    ai_set = {t.lower() for t in CONFIG["ai_tags"]}
    return any(t.lower() in ai_set or
               any(ai in t.lower() for ai in ai_set)
               for t in tags)


def classify_by_tag(tags, is_r18):
    """根据标签确定目标文件夹名。
    返回 (tag_folder_name, r18_subfolder) 的元组。
    - tag_folder_name: 匹配到的标签文件夹名，None 表示不分类
    - r18_subfolder: R18 子文件夹名，空字符串表示不分 R18 子目录
    """
    org = CONFIG.get("organize_by_tags")

    # 辅助：按 separate_r18 配置决定 R18 子目录
    def _r18_sub():
        if not CONFIG.get("separate_r18"):
            return ""
        return "r18" if is_r18 else "safe"

    if not org or not tags:
        return None, _r18_sub()

    ai_set = {t.lower() for t in CONFIG.get("ai_tags", [])}

    if isinstance(org, list) and org:
        # 指定标签列表：按顺序匹配
        target_set = {t.lower() for t in org}
        for t in tags:
            if t.lower() in target_set:
                return sanitize(t), _r18_sub()
        # 不匹配任何指定标签 → 归入 "其他"
        return "其他", _r18_sub()
    elif isinstance(org, list):
        # 空列表 = 不分类
        return None, _r18_sub()

    # organize_by_tags == True: 使用第一个非 AI 标签
    for t in tags:
        tl = t.lower()
        if tl not in ai_set and not any(ai in tl for ai in ai_set):
            return sanitize(t), _r18_sub()
    # 全部是 AI 标签 → 归入 "AI"
    return "AI", _r18_sub()


