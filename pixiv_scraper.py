# GUI/外部调用钩子
_log_callback = None       # 日志回调: fn(str)
_stop_flag = False         # 停止标志


def _log(msg):
    # 同时输出到控制台和 GUI 回调（windowed exe 中 stdout 为 None，需保护）
    try:
        print(msg)
    except (OSError, AttributeError):
        pass
    if _log_callback:
        try:
            _log_callback(msg)
        except Exception:
            pass


def _should_stop():
    # 检查是否请求停止
    return _stop_flag


def stop_scraper():
    # 请求停止爬虫
    global _stop_flag
    _stop_flag = True


def run_scraper(config_override=None, log_callback=None):
    # 可外部调用的入口，返回 {"ok": True/False, ...}
    global _log_callback, _stop_flag, CONFIG
    _log_callback = log_callback
    _stop_flag = False
    original = dict(CONFIG)
    if config_override:
        CONFIG.update(config_override)
    try:
        return _main_impl()
    finally:
        CONFIG.clear()
        CONFIG.update(original)
        _log_callback = None
        _stop_flag = False


def _main_impl():
    org_tags = CONFIG.get("organize_by_tags")
    org_str = ""
    if isinstance(org_tags, list) and org_tags:
        org_str = " | 标签分类: " + ", ".join(org_tags)
    elif org_tags:
        org_str = " | 标签分类: 自动(首个非AI标签)"

    sep = "=" * 60
    r18_mode = "仅R18" if CONFIG.get("r18_only") else ("不含R18" if not CONFIG.get("include_r18", True) else "含R18")
    _log(f"\n{sep}\n  Pixiv Scraper\n  标签: {CONFIG['tag']}"
         f" | 排序: {CONFIG['order']} | 目标: {CONFIG['max_images']} 张"
         f"\n  最低点赞: {CONFIG['min_likes']} | AI过滤: {CONFIG['filter_ai']}"
         f" | R18分夹: {CONFIG['separate_r18']} | R18模式: {r18_mode}"
         f" | 查重: {'开' if CONFIG.get('dedup') else '关'}{org_str}"
         f"\n{sep}")

    os.makedirs(CONFIG["download_dir"], exist_ok=True)

    # 无 Cookie 文件时强制显示浏览器，以便手动登录
    if not os.path.exists(CONFIG["cookie_file"]):
        CONFIG["show_browser"] = True
        _log("[*] 未找到 Cookie 文件，将打开浏览器进行手动登录")

    # 打开查重库并与磁盘对账（手动删除的图片会在这里被检测到）
    history = None
    if CONFIG.get("dedup", True):
        try:
            history = HistoryStore(CONFIG["history_db"],
                                   skip_filtered=CONFIG.get("dedup_skip_filtered", True))
            history.open()
            _log(f"[*] 查重库: {CONFIG['history_db']} | {history.summary()}")
            changed = history.reconcile()
            if changed:
                _log(f"[*] 查重: {changed} 条记录的文件被删除/恢复，已更新状态")
        except Exception as e:
            _log(f"[!] 查重库打开失败（本次不做去重）: {e}")
            history = None

    driver = None
    try:
        driver = create_driver()
        driver.maximize_window()


        if _should_stop():
            return {"ok": False, "reason": "用户停止"}

        ensure_logged_in(driver)

        if _should_stop():
            return {"ok": False, "reason": "用户停止"}

        api = build_session(driver)
        if _session_logged_in(api) is True:
            _log("[✓] 登录状态: 已登录")
        else:
            _log("[!] 登录状态: 未登录（游客）！R18 作品不会出现在搜索结果中。")
            _log("    解决: 删除 cookies.pkl 后重新运行并完成登录; 并确认 pixiv")
            _log("    「设置 → 閲覧設定 → R-18作品の表示」已开启。")

        if _should_stop():
            return {"ok": False, "reason": "用户停止"}

        _log("\n[*] 搜索作品...")
        if CONFIG.get("r18_only"):
            search_modes = ["r18"]                 # 仅 R18: 直接用 R18 搜索
        elif CONFIG.get("include_r18", True):
            search_modes = ["all", "r18"]          # 含 R18: 补一轮 R18 搜索, 避免漏掉 R18 作品
        else:
            search_modes = ["all"]
        target = CONFIG["max_images"]
        candidates, seen = [], set()
        pages = {m: 1 for m in search_modes}       # 各 mode 下一待翻页码
        mode_done = {m: False for m in search_modes}
        processed = set()                          # 已走过详情筛选的候选 id
        r18_cand = 0
        skipped_dup = 0
        pages_scanned = 0

        min_likes = CONFIG["min_likes"]
        include_r18 = CONFIG["include_r18"]
        r18_only = CONFIG.get("r18_only", False)
        mode_label = ("仅R18" if r18_only else ("不含R18" if not include_r18 else "含R18"))
        _log(f"\n[*] 获取详情 (≥{min_likes}赞, 过滤AI, {mode_label})...")

        details = []
        stats = {"low": 0, "ai": 0, "noimg": 0, "r18": 0, "safe": 0}

        # 关键：筛选出的作品不足目标数量时，继续翻页扩大扫描，直到满足 / 搜索穷尽
        while len(details) < target:
            # ---- 补充候选：保证“未处理候选”至少有 target 个（每个 mode 至少翻过第 1 页）----
            for mode in search_modes:
                while (len(candidates) - len(processed) < target or pages[mode] == 1) \
                        and not mode_done[mode] and pages[mode] <= 50:
                    if _should_stop():
                        return {"ok": False, "reason": "用户停止"}
                    items = search_api(api, CONFIG["tag"], CONFIG["order"],
                                       pages[mode], mode)
                    pages_scanned += 1
                    if not items:
                        _log(f"  [{mode}] 第 {pages[mode]} 页无结果，结束")
                        mode_done[mode] = True
                        break
                    added = dup = 0
                    for it in items:
                        if it["illust_id"] in seen:
                            continue
                        seen.add(it["illust_id"])
                        if it.get("illust_type") == 1:
                            continue                      # 漫画暂不下载
                        if history and history.should_skip(
                                it["illust_id"], it.get("illust_type") == 2)[0]:
                            dup += 1
                            skipped_dup += 1
                            continue
                        candidates.append(it)
                        if it.get("x_restrict"):
                            r18_cand += 1
                        added += 1
                    if added or dup:
                        _log(f"  [{mode}] 第 {pages[mode]} 页: 新增 {added}，查重跳过 {dup}"
                             f" (累计新 {len(candidates)}，共跳过 {skipped_dup})")
                    else:
                        mode_done[mode] = True        # 整页都是见过的条目（翻页未生效）
                        break
                    pages[mode] += 1
                    time.sleep(CONFIG["api_delay"])

            # ---- 详情筛选：处理所有尚未筛选的候选 ----
            for c in candidates:
                if c["illust_id"] in processed:
                    continue
                if _should_stop():
                    return {"ok": False, "reason": "用户停止"}
                processed.add(c["illust_id"])
                d = detail_api(api, c["illust_id"])
                d["title"] = d["title"] or c.get("title", "")
                d["author"] = d["author"] or c.get("user_name", "")
                d["author_id"] = d["author_id"] or c.get("user_id", "")
                likes = d["like_count"]
                imgs = len(d["image_urls"])

                if min_likes and likes < min_likes:
                    stats["low"] += 1
                    lbl = f"x {likes}赞"
                    if history:
                        history.record_filtered(d, "low_likes")
                elif imgs == 0:
                    stats["noimg"] += 1
                    lbl = "x 无图"      # 不写入查重库: 可能是临时失败, 下次重试
                elif CONFIG["filter_ai"] and has_ai_tag(d["tags"]):
                    stats["ai"] += 1
                    lbl = "x AI"
                    if history:
                        history.record_filtered(d, "ai")
                elif not include_r18 and d["is_r18"]:
                    stats["r18"] += 1
                    lbl = "x R18"
                    if history:
                        history.record_filtered(d, "r18_excluded")
                elif r18_only and not d["is_r18"]:
                    stats["safe"] += 1
                    lbl = "x 非R18"
                    if history:
                        history.record_filtered(d, "safe_excluded")
                else:
                    lbl = f"OK likes{likes} {imgs}图"
                    details.append(d)

                _log(f"  [{len(processed)}/{len(candidates)}] {c['illust_id']}: "
                     f"{c['title'][:30]} {lbl}")
                time.sleep(CONFIG["api_delay"])

                if stats["low"] >= 20 and len(details) >= target:
                    _log("  [*] 足够候选，停止详情获取")
                    break
                if len(details) >= target * 3:
                    _log("  [*] 候选充足，停止详情获取")
                    break

            if len(details) >= target:
                break
            if all(mode_done[m] or pages[m] > 50 for m in search_modes):
                _log(f"[*] 搜索结果已穷尽（共扫描 {pages_scanned} 页）")
                break

        if skipped_dup:
            _log(f"[*] 查重: 跳过 {skipped_dup} 个已处理过的作品")
        _log(f"\n[*] 共收集 {len(candidates)} 个作品（其中标记 R18 的 {r18_cand} 个）"
             f"，已扫描 {pages_scanned} 页")
        if not candidates:
            if skipped_dup:
                _log("[*] 没有新作品：搜索范围内的作品都已处理过（查重跳过）")
                return {"ok": True, "downloaded": 0, "total_collected": 0,
                        "skipped_dup": skipped_dup}
            _log("[!] 无结果，请检查标签名或登录状态")
            return {"ok": False, "reason": "无搜索结果"}
        if CONFIG.get("include_r18", True) and r18_cand == 0:
            _log("[!] 搜索结果里没有 R18 作品：可能是未登录（游客）、Cookie 失效，")
            _log("    或账号未开启「R-18作品の表示」（设置 → 閲覧設定）。")

        _log(f"\n[*] 低赞:{stats['low']} AI:{stats['ai']} 无图:{stats['noimg']}"
             f" R18跳过:{stats['r18']} 非R18跳过:{stats['safe']} -> 有效:{len(details)}")
        if len(details) < target:
            _log(f"[!] 满足条件的作品只有 {len(details)} 个（目标 {target}）："
                 f"已尽力扩大扫描，可尝试降低最低点赞或关闭 AI 过滤")

        if _should_stop():
            return {"ok": False, "reason": "用户停止"}

        if not details:
            _log("[*] 没有符合条件的作品可下载")
            return {"ok": True, "downloaded": 0, "skipped_dup": skipped_dup}

        details.sort(key=lambda x: x["like_count"], reverse=True)
        if details:
            ls = [d["like_count"] for d in details]
            _log(f"[*] 点赞范围: {min(ls)} ~ {max(ls)}, 平均: {sum(ls)//len(ls)}")

        _log(f"\n[*] 开始下载...")
        dl = 0
        meta = []
        base = os.path.join(CONFIG["download_dir"], sanitize(CONFIG["tag"]))

        for d in details:
            if _should_stop():
                _log("\n[*] 用户停止下载")
                break
            if dl >= CONFIG["max_images"]:
                break

            is_r18 = d["is_r18"]
            if is_r18 and not CONFIG["include_r18"]:
                continue
            if not is_r18 and CONFIG.get("r18_only", False):
                continue

            folder = os.path.join(base, "r18" if is_r18 else "safe")
            os.makedirs(folder, exist_ok=True)

            lid = d["illust_id"]
            likes = d["like_count"]
            author = d["author"]
            title = d["title"]
            urls = d["image_urls"]
            ref = d["url"]

            # 旧文件索引：点赞数变化会导致文件名变化，按页号沿用旧文件
            old_by_page = {}
            if history:
                for old_f in history.files_of(lid):
                    m = re.search(rf"_{re.escape(lid)}_p(\d+)_", os.path.basename(old_f))
                    if m:
                        old_by_page[int(m.group(1))] = old_f

            ok_cnt = 0
            saved = []
            is_ugoira = d.get("illust_type") == 2
            total_pages = 1 if is_ugoira else len(urls)

            if is_ugoira:
                # 动图：下载帧序列 zip → 合成为可播放的 GIF
                gif_path = download_ugoira(d, folder, api)
                if gif_path:
                    ok_cnt = 1
                    saved.append(gif_path)
            else:
                for j, img_url in enumerate(urls):
                    if _should_stop():
                        break
                    ext = os.path.splitext(img_url.split("?")[0])[1] or ".jpg"
                    if ext not in (".jpg", ".jpeg", ".png", ".gif", ".webp"):
                        ext = ".jpg"
                    fname = f"{likes:>08d}_{lid}_p{j}_{sanitize(author)}{ext}"
                    fpath = os.path.join(folder, fname)
                    if _file_ok(fpath):                      # 已存在 → 跳过下载
                        ok_cnt += 1
                        saved.append(fpath)
                        continue
                    of = old_by_page.get(j)                  # 沿用旧文件名（若还在）
                    if of and _file_ok(of):
                        ok_cnt += 1
                        saved.append(of)
                        continue
                    if download_image(img_url, fpath, ref, api):
                        ok_cnt += 1
                        saved.append(fpath)
                    time.sleep(CONFIG["download_delay"])

            if history and ok_cnt:
                history.record_downloaded(d, folder, saved, total_pages)

            if ok_cnt:
                dl += 1
                meta.append({"illust_id": lid, "title": title, "author": author,
                             "author_id": d["author_id"], "like_count": likes,
                             "view_count": d.get("view_count", 0),
                             "bookmark_count": d.get("bookmark_count", 0),
                             "is_r18": is_r18, "tags": d["tags"], "url": ref,
                             "ok": ok_cnt, "total": total_pages})
                r18s = " [R18]" if is_r18 else " [safe]"
                kind = " [动图]" if is_ugoira else ""
                _log(f"  [{dl}/{CONFIG['max_images']}]{r18s}{kind} likes {likes:>6} "
                     f"{title[:40]} | {ok_cnt}/{total_pages}")

            if dl >= CONFIG["max_images"]:
                break

        mp = os.path.join(base, "metadata.json")
        with open(mp, "w", encoding="utf-8") as f:
            json.dump(meta, f, ensure_ascii=False, indent=2)

        _log(f"\n{sep}\n  完成！下载 {dl} 个作品\n  目录: {os.path.abspath(base)}\n{sep}")
        if meta:
            _log("\n  Top 10:")
            for r, m in enumerate(meta[:10], 1):
                _log(f"  {r:2d}. likes {m['like_count']:>8,}  {m['title'][:45]}  by {m['author']}")

        return {"ok": True, "downloaded": dl, "total_collected": len(details),
                "skipped_dup": skipped_dup}

    except Exception as e:
        tb = traceback.format_exc()
        _log(f"\n[!] 错误: {e}\n{tb}")
        return {"ok": False, "reason": str(e), "traceback": tb}
    finally:
        if history is not None:
            try:
                history.close()
            except Exception:
                pass
        if driver is not None:
            try:
                driver.quit()
            except Exception:
                pass


if __name__ == "__main__":
    _main_impl()
